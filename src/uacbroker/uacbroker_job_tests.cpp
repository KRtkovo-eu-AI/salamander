void CheckCompetingCopyJobs(const Directory& first, const Directory& second, const Directory& target)
{
    constexpr wchar_t leaf[] = L"\u6771-shared-target";
    const auto start = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    JobPipe firstJob, secondJob;
    if (!start || !WriteByte(first.File(leaf), 6) || !WriteByte(second.File(leaf), 7) ||
        !firstJob.Open() || !secondJob.Open())
    {
        Check(false, "prepare concurrent copy jobs for one destination");
        return;
    }

    DWORD firstError = ERROR_GEN_FAILURE, secondError = ERROR_GEN_FAILURE;
    bool firstReply = false, secondReply = false;
    std::thread firstRequest([&] {
        firstReply = WaitForSingleObject(start.get(), timeoutMs) == WAIT_OBJECT_0 &&
                     firstJob.Request(Operation::Copy, first, leaf, firstError, &target);
    });
    std::thread secondRequest([&] {
        secondReply = WaitForSingleObject(start.get(), timeoutMs) == WAIT_OBJECT_0 &&
                      secondJob.Request(Operation::Copy, second, leaf, secondError, &target);
    });
    const bool started = SetEvent(start.get()) != FALSE;
    firstRequest.join();
    secondRequest.join();

    const auto isCollision = [](DWORD error) {
        return error == ERROR_ALREADY_EXISTS || error == ERROR_FILE_EXISTS;
    };
    const bool firstWon = firstError == ERROR_SUCCESS && isCollision(secondError) && HasByte(target.File(leaf), 6);
    const bool secondWon = secondError == ERROR_SUCCESS && isCollision(firstError) && HasByte(target.File(leaf), 7);
    Check(started && firstReply && secondReply && (firstWon || secondWon) &&
              HasByte(first.File(leaf), 6) && HasByte(second.File(leaf), 7),
          "two scoped copy jobs publish exactly one destination and preserve both sources");
}

void CheckActiveOverwriteJournal(const Directory& source, const Directory& target)
{
    constexpr wchar_t leaf[] = L"locked-overwrite-journal";
    const auto journalName = DiskOverwriteJournalName(target.identity);
    auto journal = Adopt(CreateFileW(journalName.c_str(), GENERIC_READ | GENERIC_WRITE, 0, nullptr,
                                    CREATE_NEW, FILE_ATTRIBUTE_NORMAL, nullptr));
    JobPipe job;
    if (!journal || !WriteByte(source.File(leaf), 47) || !job.Open())
    {
        Check(false, "prepare a copy while a competing overwrite holds the parent journal");
        return;
    }

    DWORD error = ERROR_GEN_FAILURE;
    Check(job.Request(Operation::Copy, source, leaf, error, &target) &&
              error == ERROR_SHARING_VIOLATION && IsAbsent(target.File(leaf)) && HasByte(source.File(leaf), 47),
          "an already locked overwrite journal blocks publication by a competing broker");
    journal.reset();
    Check(DeleteFileW(journalName.c_str()) &&
              job.Request(Operation::Copy, source, leaf, error, &target) && !error &&
              HasByte(target.File(leaf), 47) && HasByte(source.File(leaf), 47),
          "the same job can copy after the competing journal is released");
}

void CheckLateOverwriteJournal(const Directory& source, const Directory& target)
{
    constexpr wchar_t leaf[] = L"late-overwrite-journal";
    const auto path = target.File(leaf);
    const auto journalName = DiskOverwriteJournalName(target.identity);
    const auto staged = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    const auto resume = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    const auto backupRenamed = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    const auto finishReplacement = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    const UacCopyLeaf::Detail::CopyPause pause{staged.get(), resume.get()};
    const UacCopyLeaf::Detail::CopyPause replacementPause{backupRenamed.get(), finishReplacement.get()};
    JobPipe job;
    if (!staged || !resume || !backupRenamed || !finishReplacement || !WriteByte(source.File(leaf), 51) ||
        !job.Open(nullptr, nullptr, Operation::FindContent, &pause))
    {
        Check(false, "prepare a copy that pauses after passing the initial journal check");
        return;
    }

    DWORD error = ERROR_GEN_FAILURE;
    bool replied = false;
    std::thread copy([&] { replied = job.Request(Operation::Copy, source, leaf, error, &target); });
    const bool copying = WaitForSingleObject(staged.get(), timeoutMs) == WAIT_OBJECT_0;
    UacZipUpdate::PublishResult publication{ERROR_GEN_FAILURE};
    std::thread overwrite;
    if (copying)
    {
        overwrite = std::thread([&] {
            const ComApartment com;
            const InstallLocation install(Adopt(CreateFileW(L".", FILE_TRAVERSE | FILE_READ_ATTRIBUTES,
                FILE_SHARE_READ | FILE_SHARE_WRITE, nullptr, OPEN_EXISTING,
                FILE_FLAG_BACKUP_SEMANTICS | FILE_FLAG_OPEN_REPARSE_POINT, nullptr)));
            Handle journal;
            if (FAILED(com.result) || !install.DirectoryHandle() || !WriteByte(path, 61) ||
                OpenProtectedJournal(install, journalName, FILE_OPEN_IF, true, journal))
                return;
            const RemoveEmptyZipJournal retire{journal};
            HANDLE raw = nullptr;
            if (UacZipUpdate::Detail::Open(target.handle.get(), leaf, raw, DELETE))
                return;
            UacZipUpdate::Handle original(raw, CloseHandle);
            UacF7::ArchiveRevision revision{};
            std::wstring stageName;
            if (UacZipUpdate::ReadRevision(original.get(), revision) ||
                UacCopyLeaf::Detail::StageFile(target.handle.get(), raw, stageName, false, nullptr, true))
                return;
            const auto stage = Adopt(raw);
            const BYTE replacement = 71;
            DWORD written = 0;
            if (!WriteFile(stage.get(), &replacement, sizeof(replacement), &written, nullptr) ||
                written != sizeof(replacement))
                return;
            UacRenameLeaf::Detail::activeReplacementPause = &replacementPause;
            publication = UacZipUpdate::Publish(target.handle.get(), target.identity, leaf, revision, original,
                stage.get(), journal.get(), nullptr, MAXULONGLONG, nullptr, UacZipUpdate::ReplacementKind::DiskCopy);
        });
    }
    const bool inGap = copying && WaitForSingleObject(backupRenamed.get(), timeoutMs) == WAIT_OBJECT_0 &&
        IsAbsent(path);
    const bool released = SetEvent(resume.get()) != FALSE;
    copy.join();
    const bool copyRefused = inGap && released && replied && error == ERROR_SHARING_VIOLATION && IsAbsent(path);
    SetEvent(finishReplacement.get());
    if (overwrite.joinable())
        overwrite.join();
    Check(copyRefused && HasByte(source.File(leaf), 51),
          "an actual late overwrite keeps the staged copy out of the temporary name gap");
    Check(!publication.error && !publication.recoveryError && HasByte(path, 71) && IsAbsent(journalName),
          "the competing overwrite completes and clears the journal");
    Check(job.Request(Operation::Copy, source, leaf, error, &target) &&
              (error == ERROR_ALREADY_EXISTS || error == ERROR_FILE_EXISTS) && HasByte(path, 71),
          "the original copy session sees the newly published file as an ordinary collision");
}

void CheckStaleOverwriteJob(const Directory& source, const Directory& target)
{
    constexpr wchar_t leaf[] = L"\u6771-overwrite";
    const auto targetPath = target.File(leaf);
    const auto formerPath = target.File(L"former-overwrite");
    UacF7::ArchiveRevision approved{};
    const auto readRevision = [&] {
        const auto file = Adopt(CreateFileW(targetPath.c_str(), FILE_READ_ATTRIBUTES, FILE_SHARE_READ,
                                            nullptr, OPEN_EXISTING, FILE_FLAG_OPEN_REPARSE_POINT, nullptr));
        return file && !UacZipUpdate::ReadRevision(file.get(), approved);
    };
    JobPipe job;
    if (!WriteByte(source.File(leaf), 8) || !WriteByte(targetPath, 9) || !readRevision() ||
        !MoveFileExW(targetPath.c_str(), formerPath.c_str(), 0) || !WriteByte(targetPath, 10) || !job.Open())
    {
        Check(false, "prepare a replaced overwrite target after capturing its revision");
        return;
    }

    DWORD error = ERROR_GEN_FAILURE;
    // A directory listing can lag even when the selected NTFS object has not
    // changed. Model that deterministically without waiting for cache timing:
    // the supplied receipt keeps the real file ID but has an older timestamp.
    const UacF7::ArchiveRevision originalApproval = approved;
    UacF7::ArchiveRevision staleTimestamp{};
    UacF7::ArchiveRevision beforeTimestamp{}, afterTimestamp{};
    // The original has already moved to formerPath; inspect the replacement
    // instead, then perturb just its listed timestamp for the request.
    const bool replacementCaptured = readRevision();
    staleTimestamp = approved;
    staleTimestamp.modified ^= 1;
    beforeTimestamp = approved;
    const bool refusedTimestamp = replacementCaptured && job.Request(Operation::CopyOverwrite, source, leaf, error, &target,
        nullptr, nullptr, false, nullptr, &staleTimestamp) && error == ERROR_FILE_INVALID;
    const bool capturedAfter = readRevision();
    afterTimestamp = approved;
    Check(refusedTimestamp && capturedAfter && UacF7::SameFileRevision(beforeTimestamp, afterTimestamp) &&
              HasByte(targetPath, 10) && HasByte(formerPath, 9) && HasByte(source.File(leaf), 8),
          "stale listed timestamp on the same target identity refuses overwrite and preserves both files");
    // Continue with the initially approved identity to test replacement.
    approved = originalApproval;
    Check(job.Request(Operation::CopyOverwrite, source, leaf, error, &target,
                      nullptr, nullptr, false, nullptr, &approved) &&
              error == ERROR_FILE_INVALID && HasByte(targetPath, 10) && HasByte(formerPath, 9) && HasByte(source.File(leaf), 8),
          "an overwrite approval cannot replace a newly substituted file");
    Check(readRevision() && SetFileAttributesW(targetPath.c_str(), FILE_ATTRIBUTE_HIDDEN) &&
              job.Request(Operation::CopyOverwrite, source, leaf, error, &target,
                          nullptr, nullptr, false, nullptr, &approved) &&
              error == ERROR_FILE_INVALID && HasByte(targetPath, 10) &&
              (GetFileAttributesW(targetPath.c_str()) & FILE_ATTRIBUTE_HIDDEN),
          "the same broker rejects a revised target with the same file identity");
}

void CheckIgnoreAdsOverwriteJob(const Directory& source, const Directory& target)
{
    constexpr wchar_t first[] = L"ignore-job-first";
    constexpr wchar_t leaf[] = L"ignore-job-overwrite-東";
    if (!WriteByte(source.File(first), 1) || !WriteByte(source.File(leaf), 2) || !WriteByte(target.File(leaf), 3))
    { Check(false, "prepare an ignored-stream overwrite job"); return; }
    UacF7::ArchiveRevision approved{};
    const auto original = Adopt(CreateFileW(target.File(leaf).c_str(), FILE_READ_ATTRIBUTES,
        FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE, nullptr, OPEN_EXISTING,
        FILE_FLAG_OPEN_REPARSE_POINT, nullptr));
    if (!original || UacZipUpdate::ReadRevision(original.get(), approved))
    { Check(false, "capture an ignored-stream overwrite revision"); return; }
    JobPipe job;
    DWORD error = ERROR_GEN_FAILURE;
    if (!job.Open() || !job.Request(Operation::CopyIgnoreAds, source, first, error, &target) || error)
    { Check(false, "start an ignored-stream copy job"); return; }
    const bool changed = SetFileAttributesW(target.File(leaf).c_str(), FILE_ATTRIBUTE_HIDDEN) != FALSE;
    error = ERROR_GEN_FAILURE;
    Check(changed && job.Request(Operation::CopyOverwriteIgnoreAds, source, leaf, error, &target,
                                 nullptr, nullptr, false, nullptr, &approved) && error == ERROR_FILE_INVALID &&
          HasByte(source.File(leaf), 2) && HasByte(target.File(leaf), 3),
          "reuse ignored-stream consent but reject a changed overwrite target");
    UacF7::TransferJobScope normal{}, ignored{};
    normal.operation = Operation::Copy;
    ignored.operation = Operation::CopyIgnoreAds;
    auto ignoredOverwrite = ignored;
    ignoredOverwrite.operation = Operation::CopyOverwriteIgnoreAds;
    Check(ignored.Matches(ignoredOverwrite) && !normal.Matches(ignoredOverwrite) &&
          !ignored.Matches(normal), "ignored-stream and ordinary copy consents do not cross");
    Check(UacF7::NeedsDiskRecoveryWarning(Operation::CopyOverwriteIgnoreAds, {ERROR_BROKEN_PIPE, true}) &&
          UacF7::NeedsDiskRecoveryWarning(Operation::Copy, {ERROR_PARTIAL_COPY, true}) &&
          UacF7::NeedsDiskRecoveryWarning(Operation::MoveOverwrite, {ERROR_BROKEN_PIPE, true}) &&
          !UacF7::NeedsDiskRecoveryWarning(Operation::CopyOverwriteIgnoreAds, {ERROR_BROKEN_PIPE, false}) &&
          !UacF7::NeedsDiskRecoveryWarning(Operation::CopyEncrypted, {ERROR_BROKEN_PIPE, true}) &&
          !UacF7::NeedsDiskRecoveryWarning(Operation::Move, {ERROR_BROKEN_PIPE, true}),
          "warn about disk recovery on uncertain replies only for matching operation types");
}

void CheckMoveOverwriteJob(const Directory& source, const Directory& target, const Directory& outside)
{
    constexpr wchar_t fresh[] = L"move-job-fresh";
    constexpr wchar_t replace[] = L"move-job-replace-東";
    constexpr wchar_t denied[] = L"move-job-outside";
    constexpr wchar_t stale[] = L"move-job-stale";
    const auto revisionOf = [&](const wchar_t* name, UacF7::ArchiveRevision& revision) {
        const auto file = Adopt(CreateFileW(target.File(name).c_str(), FILE_READ_ATTRIBUTES,
            FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE, nullptr, OPEN_EXISTING, FILE_FLAG_OPEN_REPARSE_POINT, nullptr));
        return file && !UacZipUpdate::ReadRevision(file.get(), revision);
    };
    UacF7::ArchiveRevision revision{};
    FILE_ID_INFO originalSource{};
    JobPipe job;
    if (!WriteByte(source.File(fresh), 1) || !WriteByte(source.File(replace), 2) ||
        !WriteByte(source.File(stale), 3) || !WriteByte(source.File(denied), 4) ||
        !WriteByte(target.File(replace), 9) || !WriteByte(target.File(stale), 8) ||
        !SetFileAttributesW(target.File(replace).c_str(), FILE_ATTRIBUTE_READONLY | FILE_ATTRIBUTE_HIDDEN) ||
        !revisionOf(replace, revision) || !job.Open())
    { Check(false, "prepare mixed native move-overwrite job"); return; }
    {
        const auto file = Adopt(CreateFileW(source.File(replace).c_str(), FILE_READ_ATTRIBUTES, FILE_SHARE_READ,
                                            nullptr, OPEN_EXISTING, FILE_FLAG_OPEN_REPARSE_POINT, nullptr));
        if (!file || !GetFileInformationByHandleEx(file.get(), FileIdInfo, &originalSource, sizeof(originalSource)))
        { Check(false, "capture source ID before overwrite move"); return; }
    }
    DWORD error = ERROR_GEN_FAILURE;
    Check(job.Request(Operation::Move, source, fresh, error, &target, nullptr, nullptr, false, nullptr, nullptr, 0) &&
              !error && IsAbsent(source.File(fresh)) && HasByte(target.File(fresh), 1),
          "begin one move job with a new destination");
    Check(job.Request(Operation::MoveOverwrite, source, replace, error, &target, nullptr, nullptr, false, nullptr, &revision, 0) &&
              !error && IsAbsent(source.File(replace)) && HasByte(target.File(replace), 2),
          "reuse the same move consent for an independently approved readonly target replacement");
    {
        const auto file = Adopt(CreateFileW(target.File(replace).c_str(), FILE_READ_ATTRIBUTES, FILE_SHARE_READ,
                                            nullptr, OPEN_EXISTING, FILE_FLAG_OPEN_REPARSE_POINT, nullptr));
        FILE_ID_INFO after{};
        Check(file && GetFileInformationByHandleEx(file.get(), FileIdInfo, &after, sizeof(after)) &&
                  UacRenameLeaf::Detail::SameSource(after, originalSource),
              "move-overwrite dispatcher publishes the original NTFS object");
    }
    Check(revisionOf(stale, revision) && SetFileAttributesW(target.File(stale).c_str(), FILE_ATTRIBUTE_HIDDEN) &&
              job.Request(Operation::MoveOverwrite, source, stale, error, &target, nullptr, nullptr, false, nullptr, &revision, 0) &&
              error == ERROR_FILE_INVALID && HasByte(source.File(stale), 3) && HasByte(target.File(stale), 8),
          "stale move overwrite approval preserves source and existing target");
    Check(!job.Request(Operation::MoveOverwrite, source, denied, error, &outside, nullptr, nullptr, false, nullptr, &revision, 0) &&
              job.Finish() == ERROR_ACCESS_DENIED && HasByte(source.File(denied), 4) && IsAbsent(outside.File(denied)),
          "overwrite operation cannot widen the consent to another parent");
    JobPipe cross;
    Check(revisionOf(stale, revision) && cross.Open() &&
              cross.Request(Operation::MoveAcrossVolumeOverwrite, source, stale, error, &target,
                            nullptr, nullptr, false, nullptr, &revision) && error == ERROR_NOT_SAME_DEVICE &&
              HasByte(source.File(stale), 3) && HasByte(target.File(stale), 8),
          "cross-volume overwrite frame carries revision and rejects same-volume misuse");
    Directory wrongSourceParent, wrongTargetParent;
    wrongSourceParent.identity = source.identity;
    wrongSourceParent.path = source.path;
    wrongSourceParent.relative = source.relative;
    wrongSourceParent.identity.file.FileId.Identifier[0] ^= 1;
    wrongTargetParent.identity = target.identity;
    wrongTargetParent.path = target.path;
    wrongTargetParent.relative = target.relative;
    wrongTargetParent.identity.file.FileId.Identifier[0] ^= 1;
    for (const auto operation : {Operation::MoveAcrossVolume, Operation::MoveAcrossVolumeOverwrite})
    {
        const auto expectedRevision = operation == Operation::MoveAcrossVolumeOverwrite ? &revision : nullptr;
        JobPipe badSource, badTarget;
        Check(badSource.Open() && badSource.Request(operation, wrongSourceParent, stale, error, &target,
                  nullptr, nullptr, false, nullptr, expectedRevision) && error == ERROR_FILE_INVALID &&
                  HasByte(source.File(stale), 3) && HasByte(target.File(stale), 8),
              "cross-volume transfer rejects a stale source parent before volume checks despite the matching source ID");
        Check(badTarget.Open() && badTarget.Request(operation, source, stale, error, &wrongTargetParent,
                  nullptr, nullptr, false, nullptr, expectedRevision) && error == ERROR_FILE_INVALID &&
                  HasByte(source.File(stale), 3) && HasByte(target.File(stale), 8),
              "cross-volume transfer rejects a stale target parent before volume checks and preserves both files");
    }
    UacF7::TransferJobScope copyScope{}, moveScope{};
    copyScope.operation = Operation::Copy;
    auto copyOverwrite = copyScope; copyOverwrite.operation = Operation::CopyOverwrite;
    moveScope.operation = Operation::Move;
    auto moveOverwrite = moveScope; moveOverwrite.operation = Operation::MoveOverwrite;
    Check(copyScope.Matches(copyOverwrite) && moveScope.Matches(moveOverwrite) && !copyScope.Matches(moveOverwrite),
          "job families reuse copy or move consent but never convert copy authorization to a move");

    const auto root = OpenVolumeRoot(target.identity.volume);
    const auto readSecurity = [](HANDLE file) {
        PSECURITY_DESCRIPTOR raw = nullptr;
        const DWORD status = GetSecurityInfo(file, SE_FILE_OBJECT, OWNER_SECURITY_INFORMATION | DACL_SECURITY_INFORMATION,
            nullptr, nullptr, nullptr, nullptr, &raw);
        const std::unique_ptr<void, LocalFreeDeleter> descriptor(raw);
        return status;
    };
    Handle metadataOnly;
    UacDirectoryLeaf::ParentIdentity actual;
    Check(root && !OpenRequestParent(root.get(), target.relative, metadataOnly, actual) &&
              readSecurity(metadataOnly.get()) == ERROR_ACCESS_DENIED,
          "a metadata-only destination handle cannot inspect the DACL required for guarded named streams");
    for (const auto operation : {Operation::MoveAcrossVolume, Operation::MoveCompressed, Operation::MoveAcrossVolumeOverwrite})
    {
        Handle inspect;
        const DWORD access = UacF7::InspectsMoveTarget(operation) ? READ_CONTROL : 0;
        Check(root && !OpenRequestParent(root.get(), target.relative, inspect, actual, access) &&
                  UacDirectoryLeaf::SameParent(actual, target.identity) && !readSecurity(inspect.get()),
              "cross-volume destination policy opens a handle that can verify its actual DACL before named-stream publication");
    }
    Check(!UacF7::InspectsMoveTarget(Operation::Copy) && !UacF7::InspectsMoveTarget(Operation::FinishCrossVolumeMove),
          "target DACL inspection remains confined to cross-volume copy publication");
}

void CheckCancelledCopyJob(const Directory& source, const Directory& outside, const Directory& target)
{
    const auto ready = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    const auto staged = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    const auto resume = Adopt(CreateEventW(nullptr, TRUE, FALSE, nullptr));
    const UacCopyLeaf::Detail::CopyPause pause{staged.get(), resume.get()};
    JobPipe job, independent;
    constexpr wchar_t pending[] = L"pending-cancel";
    constexpr wchar_t other[] = L"other-active-copy";
    constexpr wchar_t next[] = L"other-next-copy";
    if (!ready || !staged || !resume || !WriteByte(source.File(pending), 4) ||
        !WriteByte(outside.File(other), 71) || !WriteByte(outside.File(next), 72) ||
        !job.Open(ready.get()) || !independent.Open(nullptr, nullptr, Operation::FindContent, &pause))
    {
        Check(false, "prepare cancellable and independent copy jobs");
        return;
    }

    DWORD independentError = ERROR_GEN_FAILURE;
    bool independentReply = false;
    std::thread copy([&] { independentReply = independent.Request(Operation::Copy, outside, other, independentError, &target); });
    const bool otherStaged = WaitForSingleObject(staged.get(), timeoutMs) == WAIT_OBJECT_0;
    DWORD error = ERROR_GEN_FAILURE;
    const bool cancelled = job.Request(Operation::Copy, source, pending, error, &target, nullptr, nullptr, false, ready.get());
    Check(cancelled && error == ERROR_CANCELLED &&
              !job.Request(Operation::Copy, source, pending, error, &target) && job.Finish() == ERROR_SUCCESS &&
              IsAbsent(target.File(pending)) && HasByte(source.File(pending), 4),
          "a cancel control keeps the source, leaves no target and ends the scoped broker job");

    const bool otherUnpublished = IsAbsent(target.File(other));
    const bool resumed = SetEvent(resume.get()) != FALSE;
    copy.join();
    Check(otherStaged && otherUnpublished && resumed && independentReply && independentError == ERROR_SUCCESS &&
              HasByte(target.File(other), 71) && HasByte(outside.File(other), 71),
          "cancelling a different live job leaves the staged copy and its source intact");
    Check(independent.Request(Operation::Copy, outside, next, independentError, &target) &&
              independentError == ERROR_SUCCESS && HasByte(target.File(next), 72) && HasByte(outside.File(next), 72) &&
              IsAbsent(target.File(pending)) && independent.CancelIdle() == ERROR_SUCCESS,
          "the independent job retains its scope for another item and ends cleanly");
}

