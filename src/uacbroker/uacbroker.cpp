bool ProtectedObject(HANDLE handle, bool directory, bool namespaceOnly)
{
    FILE_ATTRIBUTE_TAG_INFO info{};
    if (!GetFileInformationByHandleEx(handle, FileAttributeTagInfo, &info, sizeof(info)) ||
        (info.FileAttributes & FILE_ATTRIBUTE_REPARSE_POINT) ||
        ((info.FileAttributes & FILE_ATTRIBUTE_DIRECTORY) != 0) != directory)
        return false;

    PSID owner = nullptr;
    PACL dacl = nullptr;
    PSECURITY_DESCRIPTOR raw = nullptr;
    const DWORD status = GetSecurityInfo(handle, SE_FILE_OBJECT, OWNER_SECURITY_INFORMATION | DACL_SECURITY_INFORMATION,
                                         &owner, nullptr, &dacl, nullptr, &raw);
    const std::unique_ptr<void, LocalFreeDeleter> security(raw);
    PSID installerRaw = nullptr;
    if (status != ERROR_SUCCESS || !owner || !dacl ||
        !ConvertStringSidToSidW(L"S-1-5-80-956008885-3418522649-1831038044-1853292631-2271478464", &installerRaw))
        return false;
    const std::unique_ptr<void, LocalFreeDeleter> installer(installerRaw);
    if (!TrustedSid(owner, installer.get()))
        return false;

    // Inherit-only ACEs describe descendants, which we check independently.
    constexpr DWORD commonChange = GENERIC_ALL | GENERIC_WRITE | WRITE_DAC | WRITE_OWNER | DELETE |
                                   FILE_WRITE_EA | FILE_WRITE_ATTRIBUTES | FILE_DELETE_CHILD;
    const DWORD change = commonChange | (namespaceOnly ? 0 : FILE_WRITE_DATA | FILE_APPEND_DATA);
    for (DWORD i = 0; i < dacl->AceCount; ++i)
    {
        void* entry = nullptr;
        if (!GetAce(dacl, i, &entry))
            return false;
        const auto* header = static_cast<const ACE_HEADER*>(entry);
        if (header->AceFlags & INHERIT_ONLY_ACE)
            continue;
        if (header->AceType == ACCESS_DENIED_ACE_TYPE)
            continue;
        if (header->AceType != ACCESS_ALLOWED_ACE_TYPE)
            return false;
        auto* allow = static_cast<ACCESS_ALLOWED_ACE*>(entry);
        if ((allow->Mask & change) && !TrustedSid(&allow->SidStart, installer.get()))
            return false;
    }
    return true;
}

bool ProtectedObject(HANDLE handle, bool directory)
{
    return ProtectedObject(handle, directory, false);
}

[[maybe_unused]] bool MatchesProtocolImage(const std::wstring& path, WORD expectedRole)
{
    // This maps resources without executing code or resolving its imports.
    const HMODULE image = LoadLibraryExW(path.c_str(), nullptr,
        LOAD_LIBRARY_AS_DATAFILE_EXCLUSIVE | LOAD_LIBRARY_AS_IMAGE_RESOURCE);
    if (!image)
        return false;
    const HRSRC resource = FindResourceW(image, MAKEINTRESOURCEW(SAM_UAC_PROTOCOL_RESOURCE), MAKEINTRESOURCEW(10));
    WORD marker[2]{};
    if (resource && SizeofResource(image, resource) == sizeof(marker))
    {
        const HGLOBAL data = LoadResource(image, resource);
        if (const void* bytes = data ? LockResource(data) : nullptr)
            std::memcpy(marker, bytes, sizeof(marker));
    }
    FreeLibrary(image);
    return marker[0] == protocolVersion && marker[1] == expectedRole;
}

