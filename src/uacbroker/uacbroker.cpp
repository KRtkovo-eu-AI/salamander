DWORD ListingSession::SendPath(const std::wstring& path, DWORD flags, ULONGLONG deadline)
{
    if (contentOpen || !Contains(path) || (prepared.operation == Operation::FindFile && flags != UacListing::contentRequest))
        return ERROR_ACCESS_DENIED;
    std::wstring relative = path.size() == root.size() ? std::wstring{} : path.substr(root.size() + 1);
    if (relative.size() > UacDirectoryLeaf::maxNativeName)
        return ERROR_FILENAME_EXCED_RANGE;
    DWORD request = static_cast<DWORD>(relative.size()) | flags;
    DWORD error = TransferRequest(pipe, &request, sizeof(request), true, deadline);
    if (!error && !relative.empty())
        error = TransferRequest(pipe, relative.data(), static_cast<DWORD>(relative.size() * sizeof(wchar_t)), true, deadline);
    if (error)
        Close();
    return error;
}

DWORD ListingSession::OpenContent(const std::wstring& path, ULONGLONG& size, FILETIME& modified, ArchiveRevision& revision)
{
    size = 0;
    modified = {};
    revision = {};
    if (prepared.operation != Operation::FindFile &&
        (prepared.operation != Operation::FindContent || path.size() <= root.size()))
        return ERROR_ACCESS_DENIED;
    const auto deadline = GetTickCount64() + timeoutMs;
    DWORD error = SendPath(path, UacListing::contentRequest, deadline);
    if (error)
        return error;
    DWORD status = ERROR_SUCCESS;
    error = TransferRequest(pipe, &status, sizeof(status), false, deadline);
    if (!error && !status)
    {
        error = TransferRequest(pipe, &revision, sizeof(revision), false, deadline);
        if (!error && (revision.size < 0 || revision.reserved))
            error = ERROR_INVALID_DATA;
    }
    if (error)
    {
        Close();
        return error;
    }
    if (status)
        return status;
    contentOpen = true;
    size = static_cast<ULONGLONG>(revision.size);
    LARGE_INTEGER writeTime{};
    writeTime.QuadPart = revision.modified;
    modified = UacListing::Time(writeTime);
    return ERROR_SUCCESS;
}

DWORD ListingSession::ReadContent(ULONGLONG offset, void* buffer, DWORD bytes)
{
    if (!pipe || !contentOpen || !bytes || bytes > archiveReadBlock)
        return ERROR_INVALID_PARAMETER;
    const auto deadline = GetTickCount64() + timeoutMs;
    ArchiveReadRange range{offset, bytes, 0};
    DWORD status = ERROR_SUCCESS;
    DWORD error = TransferRequest(pipe, &range, sizeof(range), true, deadline);
    if (!error)
        error = TransferRequest(pipe, &status, sizeof(status), false, deadline);
    if (!error && !status)
        error = TransferRequest(pipe, buffer, bytes, false, deadline);
    if (error)
        Close();
    return error ? error : status;
}

DWORD ListingSession::CloseContent()
{
    if (!contentOpen || !pipe)
        return ERROR_SUCCESS;
    contentOpen = false;
    ArchiveReadRange end{};
    DWORD status = ERROR_SUCCESS;
    const auto deadline = GetTickCount64() + timeoutMs;
    DWORD error = TransferRequest(pipe, &end, sizeof(end), true, deadline);
    if (!error)
        error = TransferRequest(pipe, &status, sizeof(status), false, deadline);
    if (error)
        Close();
    return error ? error : status;
}

DWORD ListingSession::Inventory(const std::wstring& path, DirectoryInventory& inventory, DirectorySizeDetails* details)
{
    inventory = {};
    if (details)
        *details = {};
    const auto deadline = GetTickCount64() + timeoutMs;
    const DWORD flags = UacListing::inventoryRequest | (details ? UacListing::sizeDetailsRequest : 0);
    DWORD error = SendPath(path, flags, deadline);
    if (error)
        return error;
    ListingReply reply{};
    error = TransferRequest(pipe, &reply, sizeof(reply), false, deadline);
    if (!error && reply.count)
        error = ERROR_INVALID_DATA;
    if (!error && !reply.error)
    {
        DirectoryInventory complete;
        error = TransferRequest(pipe, &complete, sizeof(complete), false, deadline);
        if (!error && (complete.directories > UacListing::maxEntries ||
                       complete.files > UacListing::maxEntries - complete.directories))
            error = ERROR_INVALID_DATA;
        if (!error && details)
        {
            DirectorySizeDetails measured;
            error = TransferRequest(pipe, &measured.disk, sizeof(measured.disk), false, deadline);
            if (!error && complete.files)
            {
                measured.fileSizes.resize(complete.files);
                error = TransferRequest(pipe, measured.fileSizes.data(), complete.files * sizeof(ULONGLONG), false, deadline);
            }
            ULONGLONG sum = 0;
            for (const auto size : measured.fileSizes)
            {
                if (size > complete.bytes - sum)
                {
                    error = ERROR_INVALID_DATA;
                    break;
                }
                sum += size;
            }
            if (!error && sum != complete.bytes)
                error = ERROR_INVALID_DATA;
            if (!error)
                *details = std::move(measured);
        }
        if (!error)
            inventory = complete;
    }
    if (error)
        Close();
    return error ? error : reply.error;
}

DWORD ListingSession::List(const std::wstring& path, std::vector<WIN32_FIND_DATAW>& entries)
{
    entries.clear();
    const auto deadline = GetTickCount64() + timeoutMs;
    DWORD error = SendPath(path, 0, deadline);
    if (error)
        return error;
    ListingReply reply{};
    if (!error)
        error = TransferRequest(pipe, &reply, sizeof(reply), false, deadline);
    if (!error && (reply.count > UacListing::maxEntries || (reply.error && reply.count)))
        error = ERROR_INVALID_DATA;
    if (!error && reply.count)
    {
        entries.resize(reply.count);
        error = TransferRequest(pipe, entries.data(), reply.count * static_cast<DWORD>(sizeof(WIN32_FIND_DATAW)), false, deadline);
        if (!error)
        {
            for (const auto& entry : entries)
                if (!UacDirectoryLeaf::IsComponent(std::wstring_view(entry.cFileName, wcsnlen_s(entry.cFileName, ARRAYSIZE(entry.cFileName)))))
                {
                    error = ERROR_INVALID_DATA;
                    break;
                }
        }
    }
    if (error)
    {
        entries.clear();
        Close();
        return error;
    }
    return reply.error;
}
