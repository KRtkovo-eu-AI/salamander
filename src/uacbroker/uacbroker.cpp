static Result RepeatTransferJob(HANDLE& pipe, RequestHeader& header, std::wstring& payload,
                                void* extra, DWORD extraBytes, MetadataJobPolicy* policy = nullptr, HANDLE cancel = nullptr,
                                TransferProgress progress = nullptr, void* progressContext = nullptr)
{
    Result result;
    auto deadline = GetTickCount64() + timeoutMs;
    DWORD error = SendOperationRequest(pipe, header, payload, extra, extraBytes, policy, false, deadline, result);
    if (!error)
    {
        deadline = TransferDeadline(header.operation);
        error = ReadTransferResult(pipe, result.error, deadline, cancel, progress, progressContext,
                                   header.operation);
    }
    if (error)
        result.error = error;
    else
        result = TransferReply(header.operation, result.error, true);
    if (error || !CanContinueTransferJob(result.error))
    {
        CloseHandle(pipe);
        pipe = nullptr;
    }
    return result;
}

Result PreparedLeaf::Execute(HWND owner, TransferJobSession* job, BrokerActivity notify) const
{
    Result result;
    const ComApartment com;
    InstallLocation install;
    if (!parent || FAILED(com.result) || !install.Open() ||
        !install.MatchesProcess(GetCurrentProcess(), appImage) || !install.OpenImage(appImage))
        return result;
    RequestHeader header{serial, {}, {}, operation,
                         static_cast<DWORD>(relative.size()), static_cast<DWORD>(leaf.size()),
                         static_cast<DWORD>(sourceLeaf.size()), 0, {}, 0, 0, 0};
    std::memcpy(header.parentId.Identifier, fileId, sizeof(fileId));
    std::memcpy(header.sourceId.Identifier, sourceId, sizeof(sourceId));
    std::wstring payload = volume + relative + leaf + sourceLeaf;
    MetadataChange requestMetadata = metadata;
    auto* change = operation == Operation::Metadata ? &requestMetadata : nullptr;
    auto policy = metadataPolicy;
    if (job && (!CanShareTransferJob(operation) || (change && !policy.Allows(*change))))
        return result;
    BrokerActivityScope activity(owner, notify);
    if (job && IsInJob(*job))
    {
        activity.Start();
        return RepeatTransferJob(job->pipe, header, payload, change, sizeof(requestMetadata), change ? &policy : nullptr);
    }
    if (job)
    {
        job->Close();
        job->scope = JobScope();
    }
    RunProbe(install, false, false, owner, &header, &payload, change, &result, nullptr, nullptr,
             nullptr, nullptr, nullptr, nullptr, nullptr, job ? &job->pipe : nullptr, job && change ? &policy : nullptr,
             nullptr, nullptr, &activity);
    return result;
}

