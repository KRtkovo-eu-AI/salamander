bool ElevatedEditor::Prepare(const std::wstring& command)
{
    if (!pinned.empty())
        return false;
    std::wstring resolved;
    std::wstring_view path(command);
    if (path.size() >= 2 && path.front() == L'"' && path.back() == L'"')
        path = path.substr(1, path.size() - 2);
    if (UacDirectoryLeaf::Equal(path, L"notepad.exe"))
    {
        // The built-in default uses a bare name. Resolve it without PATH or the document directory.
        PWSTR windows = nullptr;
        if (FAILED(SHGetKnownFolderPath(FOLDERID_Windows, KF_FLAG_DEFAULT_PATH, nullptr, &windows)))
            return false;
        const std::unique_ptr<wchar_t, decltype(&CoTaskMemFree)> folder(windows, CoTaskMemFree);
        resolved = std::wstring(folder.get()) + L"\\notepad.exe";
        path = resolved;
    }
    if (path.size() < 8 || path[1] != L':' || path[2] != L'\\' ||
        path.find(L'"') != std::wstring_view::npos ||
        !UacDirectoryLeaf::Equal(path.substr(path.size() - 4), L".exe"))
        return false;

    std::wstring root;
    for (const KNOWNFOLDERID* folder : {&FOLDERID_Windows, &FOLDERID_ProgramFiles, &FOLDERID_ProgramFilesX86,
                                      &FOLDERID_ProgramFilesX64})
    {
        PWSTR raw = nullptr;
        if (FAILED(SHGetKnownFolderPath(*folder, KF_FLAG_DEFAULT_PATH, nullptr, &raw)))
            continue;
        const std::wstring candidate(raw);
        CoTaskMemFree(raw);
        if (path.size() > candidate.size() && path[candidate.size()] == L'\\' &&
            UacDirectoryLeaf::Equal(path.substr(0, candidate.size()), candidate))
        {
            root = candidate;
            break;
        }
    }
    if (root.size() < 3 || GetDriveTypeW(root.substr(0, 3).c_str()) != DRIVE_FIXED)
        return false;
    auto parent = Adopt(CreateFileW(root.c_str(), FILE_READ_ATTRIBUTES | FILE_TRAVERSE | READ_CONTROL,
                                    FILE_SHARE_READ | FILE_SHARE_WRITE, nullptr, OPEN_EXISTING,
                                    FILE_FLAG_OPEN_REPARSE_POINT | FILE_FLAG_BACKUP_SEMANTICS, nullptr));
    if (!parent || !ProtectedObject(parent.get(), true))
        return false;
    std::vector<Handle> verified;
    verified.push_back(std::move(parent));

    auto relative = path.substr(root.size() + 1);
    size_t separator = relative.find(L'\\');
    while (separator != std::wstring_view::npos)
    {
        const auto component = relative.substr(0, separator);
        if (!UacDirectoryLeaf::IsComponent(component) || verified.size() == 32)
            return false;
        HANDLE raw = nullptr;
        if (UacDirectoryLeaf::Detail::NativeDirectory(verified.back().get(), component, FILE_OPEN, raw,
                                                        READ_CONTROL, nullptr, FILE_SHARE_READ | FILE_SHARE_WRITE))
            return false;
        auto child = Adopt(raw);
        if (!ProtectedObject(child.get(), true))
            return false;
        verified.push_back(std::move(child));
        relative.remove_prefix(separator + 1);
        separator = relative.find(L'\\');
    }
    if (!UacDirectoryLeaf::IsComponent(relative))
        return false;
    HANDLE raw = nullptr;
    if (UacRenameLeaf::Detail::OpenSource(verified.back().get(), relative, raw, FILE_READ_DATA | READ_CONTROL, FILE_SHARE_READ))
        return false;
    auto image = Adopt(raw);
    if (!ProtectedObject(image.get(), false))
        return false;
    verified.push_back(std::move(image));

    executable.assign(path);
    directory.assign(path.substr(0, path.rfind(L'\\')));
    pinned.reserve(verified.size());
    for (auto& handle : verified)
        pinned.push_back(handle.release());
    return true;
}

DWORD ElevatedEditor::Launch(HWND owner, const std::wstring& document) const
{
    if (pinned.empty() || document.empty() || document.find(L'"') != std::wstring::npos)
        return ERROR_INVALID_PARAMETER;
    const std::wstring arguments = L"\"" + document + L"\"";
    const ComApartment com;
    if (FAILED(com.result))
        return ERROR_GEN_FAILURE;
    SHELLEXECUTEINFOW launch{sizeof(launch)};
    launch.fMask = SEE_MASK_NOASYNC | SEE_MASK_FLAG_NO_UI;
    launch.hwnd = owner;
    launch.lpVerb = L"runas";
    launch.lpFile = executable.c_str();
    launch.lpParameters = arguments.c_str();
    launch.lpDirectory = directory.c_str();
    launch.nShow = SW_SHOWNORMAL;
    return ShellExecuteExW(&launch) ? ERROR_SUCCESS : GetLastError();
}

bool PreparedTransfer::Prepare(const std::wstring& sourcePath, const std::wstring& targetPath,
                               ULONGLONG expectedSize, Operation operation)
{
    const bool compressedMove = operation == Operation::MoveCompressed;
    const bool moving = operation == Operation::Move || compressedMove;
    if ((!moving && (!IsFileCopy(operation) || expectedSize > maxPilotCopyBytes)) ||
        !source.PrepareTarget(sourcePath, operation, {}, nullptr) ||
        !target.Prepare(targetPath))
        return false;
    const bool crossMove = moving && !UacDirectoryLeaf::Equal(source.volume, target.volume);
    if (moving && !crossMove && (compressedMove || source.serial != target.serial))
        return false;
    if (crossMove)
    {
        if (expectedSize > maxCrossVolumeMoveBytes)
            return false;
        // Keeping even an attributes-only host handle would prevent the broker
        // from proving that the sealed source has no earlier opens.
        CloseHandle(source.source);
        source.source = nullptr;
        source.operation = compressedMove ? Operation::MoveCompressed : Operation::MoveAcrossVolume;
    }
    if (operation == Operation::CopyEncrypted)
    {
        InstallLocation install;
        UacDirectoryLeaf::ParentIdentity installed;
        if (!install.Open() || UacDirectoryLeaf::ReadParentIdentity(install.DirectoryHandle(), installed) ||
            !UacDirectoryLeaf::Equal(source.volume, installed.volume) || !UacDirectoryLeaf::Equal(target.volume, installed.volume))
            return false;
    }
    size = moving && !crossMove ? 0 : expectedSize;
    return true;
}

bool CaptureMoveFileIdentity(HANDLE file, MoveFileIdentity& identity, bool requireNtfs)
{
    if (requireNtfs)
    {
        wchar_t fs[16]{};
        if (!GetVolumeInformationByHandleW(file, nullptr, 0, nullptr, nullptr, nullptr, fs, ARRAYSIZE(fs)) ||
            !UacDirectoryLeaf::Equal(fs, L"NTFS"))
            return false;
    }
    FILE_ID_INFO native{};
    if (requireNtfs ? UacRenameLeaf::Detail::ReadSourceIdentity(file, native) != ERROR_SUCCESS
                    : !GetFileInformationByHandleEx(file, FileIdInfo, &native, sizeof(native)))
        return false;
    identity.serial = native.VolumeSerialNumber;
    std::memcpy(identity.id, native.FileId.Identifier, sizeof(identity.id));
    return true;
}

DWORD DeleteCopiedMoveSource(const std::wstring& sourcePath, const std::wstring& targetPath,
                             const MoveFileIdentity& source, const MoveFileIdentity& target)
{
    FILE_ID_INFO nativeSource{source.serial, {}}, nativeTarget{target.serial, {}};
    std::memcpy(nativeSource.FileId.Identifier, source.id, sizeof(source.id));
    std::memcpy(nativeTarget.FileId.Identifier, target.id, sizeof(target.id));
    return UacDeleteLeaf::DeleteCopiedSource(sourcePath, targetPath, nativeSource, nativeTarget);
}

bool PreparedTransfer::PrepareMoveCompletion(const std::wstring& sourcePath, const std::wstring& targetPath,
                                              ULONGLONG expectedSize, const MoveFileIdentity& copiedSource,
                                              const MoveFileIdentity& copiedTarget)
{
    if (!Prepare(sourcePath, targetPath, expectedSize, Operation::Move) || !IsCrossVolumeMove() ||
        source.serial != copiedSource.serial ||
        std::memcmp(source.sourceId, copiedSource.id, sizeof(source.sourceId)))
        return false;
    PreparedLeaf existing;
    if (!existing.PrepareView(targetPath) || existing.serial != target.serial ||
        !UacDirectoryLeaf::Equal(existing.volume, target.volume) ||
        std::memcmp(existing.fileId, target.fileId, sizeof(target.fileId)) ||
        UacZipUpdate::ReadRevision(existing.source, overwriteTarget) ||
        overwriteTarget.serial != copiedTarget.serial ||
        std::memcmp(overwriteTarget.fileId, copiedTarget.id, sizeof(copiedTarget.id)) ||
        static_cast<ULONGLONG>(overwriteTarget.size) != expectedSize || !IsPlainCopyFile(overwriteTarget.attributes))
        return false;
    source.operation = Operation::FinishCrossVolumeMove;
    return true;
}

bool CaptureOverwriteRevision(HANDLE file, ArchiveRevision& revision)
{
    ArchiveRevision current;
    if (UacZipUpdate::ReadRevision(file, current) || !IsPlainCopyFile(current.attributes) ||
        (current.attributes & (FILE_ATTRIBUTE_HIDDEN | FILE_ATTRIBUTE_SYSTEM)))
        return false;
    revision = current;
    return true;
}

bool PreparedTransfer::PrepareOverwrite(const std::wstring& sourcePath, const std::wstring& targetPath,
                                        ULONGLONG expectedSize)
{
    if (expectedSize > maxPilotCopyBytes ||
        !source.PrepareTarget(sourcePath, Operation::CopyOverwrite, {}, nullptr) ||
        !target.PrepareView(targetPath) ||
        !CaptureOverwriteRevision(target.source, overwriteTarget))
        return false;
    size = expectedSize;
    return true;
}

